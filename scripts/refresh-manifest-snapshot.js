"use strict";
/**
 * Captures the public skill surface from manifest.json into
 * manifest-snapshot.json. Run it AFTER an intentional surface change and commit
 * the new snapshot alongside that change — never to "fix" a failing
 * check-manifest-snapshot.js gate, whose breaking-change list is the thing to
 * read first. A breaking change is a surface narrowing every downstream
 * consumer needs to know about.
 *
 * Overwriting an existing snapshot takes `--commit-only` or
 * EXCEPTD_SNAPSHOT_AUDIT_ACK=1. Without either, a run whose capture differs
 * refuses and prints a diff hint, so muscle memory cannot mask a real breaking
 * change. scripts/predeploy.js names the flag where the gate fails.
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const MANIFEST_PATH = path.join(ROOT, "manifest.json");
const SNAPSHOT_PATH = path.join(ROOT, "manifest-snapshot.json");

function captureSurface(manifest) {
  const skills = (manifest.skills || []).map(s => ({
    name: s.name,
    version: s.version || null,
    triggers: [...(s.triggers || [])].sort(),
    data_deps: [...(s.data_deps || [])].sort(),
    atlas_refs: [...(s.atlas_refs || [])].sort(),
    attack_refs: [...(s.attack_refs || [])].sort(),
    framework_gaps: [...(s.framework_gaps || [])].sort(),
    rfc_refs: [...(s.rfc_refs || [])].sort(),
    cwe_refs: [...(s.cwe_refs || [])].sort(),
    d3fend_refs: [...(s.d3fend_refs || [])].sort(),
    dlp_refs: [...(s.dlp_refs || [])].sort(),
  })).sort((a, b) => a.name.localeCompare(b.name));

  return {
    _comment: "Auto-generated by scripts/refresh-manifest-snapshot.js — do not hand-edit. Public skill surface used by check-manifest-snapshot.js to detect breaking removals.",
    _generated_at: new Date().toISOString(),
    atlas_version: manifest.atlas_version || null,
    skill_count: skills.length,
    skills,
  };
}

const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, "utf8"));
const snapshot = captureSurface(manifest);
const newJson = JSON.stringify(snapshot, null, 2) + "\n";

const argv = process.argv.slice(2);
const commitOnly =
  argv.includes("--commit-only") ||
  process.env.EXCEPTD_SNAPSHOT_AUDIT_ACK === "1";

// Branch on the read RESULT, never on an existsSync-then-read probe: that is a
// check-then-use window (CodeQL js/file-system-race) where the file the guard
// decided on need not be the one read. ENOENT IS the "no prior snapshot" signal.
let current = null;
try {
  current = fs.readFileSync(SNAPSHOT_PATH, "utf8");
} catch (e) {
  if (e.code !== "ENOENT") throw e;
}
if (current !== null && !commitOnly) {
  // _generated_at changes every run, so it must not trigger the guard.
  const stripGenerated = (s) => s.replace(
    /"_generated_at":\s*"[^"]+",?\s*\n?/, ""
  );
  if (stripGenerated(current) === stripGenerated(newJson)) {
    console.log("[refresh-manifest-snapshot] snapshot unchanged — nothing to do.");
    process.exit(0); // allow:process-exit-after-stdout-write — local snapshot-refresh tool; the status line above is human-read on a TTY, not a piped --json result channel
  }
  process.stderr.write(
    "[refresh-manifest-snapshot] REFUSING to overwrite manifest-snapshot.json — " +
    "the captured surface differs from the committed snapshot.\n" +
    "  Re-run with `--commit-only` (or EXCEPTD_SNAPSHOT_AUDIT_ACK=1) to confirm " +
    "the rewrite is intentional. The check-manifest-snapshot.js gate exists to " +
    "force a deliberate decision about removed skills / triggers / refs before " +
    "the baseline is rewritten.\n"
  );
  process.exit(1); // allow:process-exit-after-stdout-write — local snapshot-refresh tool; the refusal note above goes to stderr on a TTY, not a piped --json result channel
}

fs.writeFileSync(SNAPSHOT_PATH, newJson, "utf8");

console.log(`[refresh-manifest-snapshot] wrote ${snapshot.skill_count} skills to manifest-snapshot.json`);
console.log("[refresh-manifest-snapshot] commit this file alongside the surface change.");

// A tracked SHA-256 lets check-manifest-snapshot.js catch a hand edit made
// after the refresh.
const crypto = require("crypto");
const snapshotSha = crypto.createHash("sha256").update(newJson).digest("hex");
const snapshotShaPath = path.join(ROOT, "manifest-snapshot.sha256");
fs.writeFileSync(snapshotShaPath, snapshotSha + "  manifest-snapshot.json\n", "utf8");
console.log(`[refresh-manifest-snapshot] wrote integrity hash to manifest-snapshot.sha256`);
